#!/usr/bin/env node
// wt-checks: synthesize a checks config into manifests and sync them with wtctl
// (`apply`, `diff`, and `checks watch` for hot reload).
import { spawn, type ChildProcess } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, watch, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve, sep } from "node:path";
import { pathToFileURL } from "node:url";

import { synth, type Manifest, type ProjectDef } from "./index.ts";

export const USAGE = `usage: wt-checks <synth|test|deploy|watch> [--config checks.config.ts] [--out .watchtower/checks]
       [--project <id>] [--api <url>] [--key <key>] [--prune]   (passed to wtctl; WTCTL picks the binary)
  synth   write one manifest per check and secret to --out
  test    synth, then show what deploy would change (wtctl diff); nothing is changed
  deploy  synth, then apply the manifests (wtctl apply)
  watch   synth and apply now, then again on every change to the config or the files it imports`;

/** The file that marks a directory as ours; only such a directory has stale manifests removed. */
const MARK = ".wt-checks";
const SOURCES = new Set([".ts", ".mts", ".cts", ".js", ".mjs", ".cjs", ".json"]);

export interface Opts {
  cmd: "synth" | "test" | "deploy" | "watch";
  config: string;
  out: string;
  pass: string[];
}

export function parseArgs(argv: string[]): Opts {
  const [cmd = "", ...rest] = argv;
  let config = "checks.config.ts";
  let out = join(".watchtower", "checks");
  const pass: string[] = [];
  for (let i = 0; i < rest.length; i++) {
    const a = rest[i] as string;
    const value = () => {
      const v = rest[++i];
      if (v === undefined || v.startsWith("--")) throw new Error(`${a} needs a value\n${USAGE}`);
      return v;
    };
    if (a === "--config" || a === "-c") config = value();
    else if (a === "--out" || a === "-o") out = value();
    else pass.push(a);
  }
  if (cmd !== "synth" && cmd !== "test" && cmd !== "deploy" && cmd !== "watch") throw new Error(USAGE);
  return { cmd, config: resolve(config), out: resolve(out), pass };
}

export async function loadProject(file: string): Promise<ProjectDef> {
  const mod = (await import(pathToFileURL(file).href)) as { default?: ProjectDef };
  const def = mod.default;
  if (!def || !Array.isArray(def.checks)) {
    throw new Error(`${file} must default-export defineProject({ checks: [...] })`);
  }
  return def;
}

const fileName = (m: Manifest) => `${m.kind}-${m.metadata.name}.json`;

/**
 * Writes the manifests to dir: changed files only (atomically, so a watcher never reads half a
 * file), then removes manifests no longer defined. New files land before stale ones go, so an
 * apply with --prune never sees a partial set.
 */
export function writeManifests(dir: string, manifests: Manifest[]): { written: number; removed: number } {
  if (existsSync(dir) && !existsSync(join(dir, MARK)) && readdirSync(dir).length > 0) {
    throw new Error(`${dir} is not empty and not a wt-checks output directory; pick another --out`);
  }
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, MARK), "generated by wt-checks; *.json here is rewritten on every synth\n");
  const keep = new Set<string>();
  let written = 0;
  for (const m of manifests) {
    const name = fileName(m);
    keep.add(name);
    const path = join(dir, name);
    const body = JSON.stringify(m, null, 2) + "\n";
    if (existsSync(path) && readFileSync(path, "utf8") === body) continue;
    writeFileSync(path + ".tmp", body);
    renameSync(path + ".tmp", path);
    written++;
  }
  let removed = 0;
  for (const f of readdirSync(dir)) {
    if (f.endsWith(".json") && !keep.has(f)) {
      rmSync(join(dir, f));
      removed++;
    }
  }
  return { written, removed };
}

async function synthTo(o: Opts, log: (s: string) => void): Promise<void> {
  const ms = synth(await loadProject(o.config));
  const r = writeManifests(o.out, ms);
  log(`${ms.length} manifest(s) in ${relative(process.cwd(), o.out) || "."}: ${r.written} written, ${r.removed} removed`);
}

function wtctl(args: string[]): ChildProcess {
  const bin = process.env.WTCTL || "wtctl";
  const js = /\.[cm]?js$/.test(bin) || /\.ts$/.test(bin);
  return spawn(js ? process.execPath : bin, js ? [bin, ...args] : args, { stdio: "inherit" });
}

function exitOf(child: ChildProcess): Promise<number> {
  return new Promise((done) => {
    child.on("error", (e) => {
      process.stderr.write(`wt-checks: cannot run wtctl (${e.message}); install it or set WTCTL\n`);
      done(2);
    });
    child.on("exit", (code) => done(code ?? 1));
  });
}

/**
 * Calls onChange (debounced) when a source file below root changes. Paths below an ignored
 * directory, node_modules and .git do not count. Returns the stop function.
 */
export function watchSources(root: string, ignore: string[], onChange: () => void, debounceMs = 300): () => void {
  let timer: ReturnType<typeof setTimeout> | undefined;
  const w = watch(root, { recursive: true }, (_event, name) => {
    if (!name) return;
    const abs = resolve(root, name.toString());
    const parts = relative(root, abs).split(sep);
    if (parts.includes("node_modules") || parts.includes(".git")) return;
    if (ignore.some((d) => abs === d || abs.startsWith(d + sep))) return;
    if (!SOURCES.has(extname(abs))) return;
    clearTimeout(timer);
    timer = setTimeout(onChange, debounceMs);
  });
  return () => {
    clearTimeout(timer);
    w.close();
  };
}

/** Re-synthesizes in a fresh process, so edits to files the config imports are seen too. */
function resynth(o: Opts): Promise<number> {
  const script = process.argv[1] as string;
  const child = spawn(process.execPath, [...process.execArgv, script, "synth", "--config", o.config, "--out", o.out], {
    stdio: "inherit",
  });
  return exitOf(child);
}

async function watchMode(o: Opts, log: (s: string) => void): Promise<number> {
  try {
    await synthTo(o, log);
  } catch (e) {
    log(`synth failed, waiting for the next change: ${(e as Error).message}`);
  }
  // wtctl applies now and after every manifest change; we keep the manifests current
  const child = wtctl(["checks", "watch", "-f", o.out, ...o.pass]);
  let running = false;
  let again = false;
  const run = async () => {
    if (running) {
      again = true;
      return;
    }
    running = true;
    do {
      again = false;
      log("change detected, synthesizing");
      if ((await resynth(o)) !== 0) log("synth failed, waiting for the next change");
    } while (again);
    running = false;
  };
  const stop = watchSources(dirname(o.config), [o.out], () => void run());
  const quit = () => child.kill("SIGINT");
  process.once("SIGINT", quit);
  process.once("SIGTERM", quit);
  const code = await exitOf(child);
  stop();
  return code;
}

export async function main(argv: string[], log: (s: string) => void = (s) => process.stderr.write(s + "\n")): Promise<number> {
  let o: Opts;
  try {
    o = parseArgs(argv);
  } catch (e) {
    log((e as Error).message);
    return 2;
  }
  if (o.cmd === "watch") return watchMode(o, log);
  try {
    await synthTo(o, log);
  } catch (e) {
    log(`synth failed: ${(e as Error).message}`);
    return 1;
  }
  if (o.cmd === "synth") return 0;
  return exitOf(wtctl([o.cmd === "deploy" ? "apply" : "diff", "-f", o.out, ...o.pass]));
}

const self = process.argv[1] ? resolve(process.argv[1]) : "";
if (self && (import.meta.url === pathToFileURL(self).href || self.endsWith(`${sep}wt-checks`))) {
  main(process.argv.slice(2)).then((code) => process.exit(code));
}
